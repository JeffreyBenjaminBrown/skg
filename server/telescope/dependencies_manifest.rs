use std::collections::{BTreeMap, HashMap, HashSet};
use std::io;
use std::path::{Component, Path, PathBuf};

/// Quote a value as a TOML basic string, escaping the two characters
/// that would otherwise break out of the quotes. Enough for git
/// remote URLs and skgrepo paths, which carry no control characters.
fn toml_basic_string (s : &str) -> String {
  let escaped : String =
    s . replace ('\\', "\\\\") . replace ('"', "\\\"");
  format! ("\"{}\"", escaped) }

/// One `dependencies` entry: a skgrepo a manifest's telescope sections
/// may reference, and where a receiver can fetch it.
struct DependencyEntry {
  path   : String,                    // data-root-relative directory
  remote : Option<(String, String)>,  // (remote name, fetch URL)
}

/// Render a `DependencyEntry` as one inline-table line of the
/// `dependencies` list: `{ path = "...", git-remote = "..." },`.
/// `git-remote` is omitted when the skgrepo has no remote;
/// `git-remote-name` appears only for a non-`origin` remote.
fn render_dependency_entry (entry : &DependencyEntry) -> String {
  let mut fields : String =
    format! ("path = {}", toml_basic_string (&entry . path));
  if let Some ((remote_name, remote_url)) = &entry . remote {
    fields . push_str ( & format! (
      ", git-remote = {}", toml_basic_string (remote_url) ));
    if remote_name != "origin" {
      fields . push_str ( & format! (
        ", git-remote-name = {}",
        toml_basic_string (remote_name) )); }}
  format! ("  {{ {} }},\n", fields) }

/// The publisher half. Call after config load; returns the skgrepos
/// whose manifests were (re)written.
pub fn write_dependencies_manifests (
  config : &SkgConfig,
) -> io::Result<Vec<SkgrepoName>> {
  let ladder : Vec<SkgrepoName> = config . privacy_ladder ();
  let mut written : Vec<SkgrepoName> = Vec::new ();
  for (position, name) in ladder . iter () . enumerate () {
    let Some (skgrepo) = config . skgrepos . get (name) else {
      continue; };
    if ! skgrepo . path . is_dir () { continue; }
    let dependencies : Vec<DependencyEntry> =
      ladder [..= position] . iter ()
      . filter_map ( |n| {
          let dep_skgrepo = config . skgrepos . get (n) ?;
          let path : String =
            dep_skgrepo . path
            . strip_prefix ( &config . data_root )
            . map ( |p| p . to_string_lossy () . into_owned () )
            . unwrap_or_else (
              |_| dep_skgrepo . path
                  . to_string_lossy () . into_owned () );
          Some ( DependencyEntry {
            path,
            remote : skgrepo_git_remote (&dep_skgrepo . path), } ) } )
      . collect ();
    let content : String = {
      let mut c : String = String::new ();
      c . push_str (
        "# Generated by skg; regenerated at every server start, so\n\
         # hand edits will be clobbered (that is a feature: it stays\n\
         # true to the publisher's config). Each dependency is one of\n\
         # the publisher's own Skg repos at least as public as this\n\
         # one, MOST PUBLIC FIRST, this Skg repo itself last. A\n\
         # receiver, to whom they are all foreign, folds a node with\n\
         # sections in several of them in this order. `path` is the\n\
         # data-root-relative directory; `git-remote` is where a\n\
         # receiver can fetch it (the fetch URL `git remote -v`\n\
         # prints, `origin` preferred), omitted when the Skg repo is\n\
         # not a Git repo or has no remote; `git-remote-name` names\n\
         # the remote only when it is not the conventional \"origin\".\n\
         # skg makes no use of the git-remote values itself.\n" );
      c . push_str ("dependencies = [\n");
      for entry in &dependencies {
        c . push_str ( & render_dependency_entry (entry) ); }
      c . push_str ("]\n");
      c };
    let manifest_path : PathBuf =
      skgrepo . path . join ("OTHER_SKGREPO_DEPENDENCIES.toml");
    let unchanged : bool = // byte-stability
      std::fs::read_to_string (&manifest_path)
      . map ( |old| old == content )
      . unwrap_or (false);
    if ! unchanged {
      std::fs::write (&manifest_path, content) ?; }
    written . push ( name . clone () ); }
  Ok (written) }

/// The `path` of one `dependencies` entry. New format: an inline
/// table carrying a `path` key. Older format: a bare string. Accept
/// either, so a foreign manifest still in the string shape keeps
/// ordering its folds.
fn dependency_entry_path (e : &toml::Value) -> Option<String> {
  e . as_str () . map ( str::to_string )
    . or_else ( || e . get ("path")
                . and_then ( |p| p . as_str () )
                . map ( str::to_string )) }

/// The receiver half, read when the config loads: for each foreign
/// skgrepo carrying a manifest, the receiver's foreign skgrepos it
/// lists, in its order. An entry names the receiver's foreign skgrepo
/// at the same data-root-relative path, else the one foreign skgrepo
/// with the same final path component (the folder the receiver keeps
/// a publisher's skgrepos in need not match the publisher's own
/// author folder); an entry matching neither way, or matching several
/// by final component, is skipped. Owned skgrepos are never matched:
/// an owned section never folds with a foreign one.
pub fn read_foreign_manifest_orders (
  config : &SkgConfig,
) -> Vec<ForeignManifestOrder> {
  let foreign : Vec<SkgrepoName> =
    config . ordered_skgrepos () . into_iter ()
    . filter ( |name| config . skgrepos . contains_key (name)
                      && ! config . skgrepo_is_owned (name) )
    . collect ();
  foreign . iter ()
    . filter_map ( |name| {
        let skgrepo = config . skgrepos . get (name) ?;
        let contents : String = std::fs::read_to_string (
          skgrepo . path . join ("OTHER_SKGREPO_DEPENDENCIES.toml") )
          . ok () ?;
        let entries : Vec<String> =
          toml::from_str::<toml::Value> (&contents) . ok ()
          . as_ref ()
          . and_then ( |v| v . get ("dependencies") )
          . and_then ( |d| d . as_array () )
          . map ( |arr| arr . iter ()
                  . filter_map ( dependency_entry_path )
                  . collect () )
          . unwrap_or_default ();
        let mut listed : Vec<SkgrepoName> = Vec::new ();
        for entry in &entries {
          if let Some (matched) =
            foreign_skgrepo_named_by_manifest_entry (
              config, &foreign, entry )
          { if ! listed . contains (&matched) {
              listed . push (matched); }} }
        Some ( ForeignManifestOrder {
          manifest_skgrepo : name . clone (),
          listed } ) } )
    . collect () }

/// The receiver's foreign skgrepo a manifest entry (a publisher's
/// data-root-relative path) names; see 'read_foreign_manifest_orders'.
fn foreign_skgrepo_named_by_manifest_entry (
  config  : &SkgConfig,
  foreign : &[SkgrepoName],
  entry   : &str,
) -> Option<SkgrepoName> {
  let final_component = |p : &Path| -> Option<String> {
    p . components () . next_back ()
      . and_then ( |c| match c {
        Component::Normal (s) =>
          Some ( s . to_string_lossy () . into_owned () ),
        _ => None } ) };
  let entry_path : &Path = Path::new (entry);
  let relative_path_of = |name : &SkgrepoName| -> Option<PathBuf> {
    config . skgrepos . get (name)
      . and_then ( |s| s . path . strip_prefix (&config . data_root)
                   . ok () . map ( Path::to_path_buf )) };
  if let Some (exact) = foreign . iter ()
    . find ( |name| relative_path_of (name) . as_deref ()
                    == Some (entry_path) )
  { return Some ( exact . clone () ); }
  let entry_component : String = final_component (entry_path) ?;
  let by_component : Vec<&SkgrepoName> = foreign . iter ()
    . filter ( |name| config . skgrepos . get (*name)
               . and_then ( |s| final_component (&s . path) )
               . as_deref () == Some (entry_component . as_str ()) )
    . collect ();
  match by_component . as_slice () {
    [only] => Some ( (*only) . clone () ),
    _      => None, }}

/// The startup warnings (never errors) about foreign sections:
///
/// - one per skgrepo holding an illegal section of some node -- a
///   section in a skgrepo of another owner than the node's home's
///   ('separate_illegal_sections') -- naming the first such node and
///   how many more there are. An owned one is drawn under its node as
///   an illegal edit; a foreign one is ignored.
/// - one per pair of one foreign owner's skgrepos whose manifests
///   order them oppositely (or, together, in a cycle), when some node
///   of that owner has a section in each, naming the first such node.
///   This server folds them as the more private one's manifest says.
///
/// Returned as strings so 'main' can log them and record them as
/// startup warnings, and tests can pin them.
pub fn foreign_section_warnings (
  config : &SkgConfig,
) -> Vec<String> {
  let section_pids_by_skgrepo : HashMap<SkgrepoName, HashSet<ID>> =
    section_pids_by_skgrepo (config);
  let skgrepos_by_pid : BTreeMap<ID, Vec<SkgrepoName>> = {
    let mut m : BTreeMap<ID, Vec<SkgrepoName>> = BTreeMap::new ();
    for skgrepo in config . ordered_skgrepos () {
      for pid in section_pids_by_skgrepo . get (&skgrepo) . into_iter () . flatten () {
        m . entry ( pid . clone () ) . or_default () . push ( skgrepo . clone () ); }}
    m . retain ( |_, skgrepos| skgrepos . len () > 1 );
    m };
  let home_owner_of = |skgrepos : &[SkgrepoName]| -> Option<SkgrepoOwner> {
    home_owner_of_sections (config, skgrepos . iter ()) };
  let mut warnings : Vec<String> = Vec::new ();
  { // Illegal sections, by the skgrepo holding them.
    let mut illegal_pids_by_skgrepo : BTreeMap<SkgrepoName, Vec<(ID, SkgrepoName)>> =
      BTreeMap::new ();
    for (pid, skgrepos) in &skgrepos_by_pid {
      let Some (home_owner) = home_owner_of (skgrepos) else { continue; };
      let Some (home) : Option<&SkgrepoName> = skgrepos . iter ()
        . find ( |skgrepo| config . skgrepo_owner (skgrepo) == home_owner )
        else { continue; };
      for skgrepo in skgrepos {
        if config . skgrepo_owner (skgrepo) != home_owner {
          illegal_pids_by_skgrepo . entry ( skgrepo . clone () ) . or_default ()
            . push (( pid . clone (), home . clone () )); }} }
    for skgrepo in config . ordered_skgrepos () {
      let Some (pids) = illegal_pids_by_skgrepo . get (&skgrepo) else { continue; };
      let (example_pid, home) : &(ID, SkgrepoName) = &pids [0];
      warnings . push ( format! (
        "Node {}{} has a section in {} '{}', but its home '{}' has another owner: an illegal edit to a foreign node. {}",
        node_named (config, example_pid, home), more_nodes (pids . len ()),
        if config . skgrepo_is_owned (&skgrepo) { "your repo" } else { "foreign repo" },
        skgrepo, home,
        if config . skgrepo_is_owned (&skgrepo) {
          "Skg shows that section only under the node, as an ILLEGAL EDIT TO FOREIGN NODE child; move what it says into a node of your own and delete the file." }
        else {
          "Skg ignores that section." } )); }}
  { // Disputed orders within one foreign owner's telescopes.
    let fold_order : Vec<SkgrepoName> =
      config . ordered_skgrepos () . into_iter ()
      . filter ( |name| config . skgrepos . contains_key (name)
                        && ! config . skgrepo_is_owned (name) )
      . collect ();
    for (i, first) in fold_order . iter () . enumerate () {
      for second in &fold_order [i + 1 ..] {
        if config . skgrepo_owner (first) != config . skgrepo_owner (second) {
          continue; }
        let pair_order : ForeignPairOrder =
          config . foreign_pair_order (first, second);
        let unsettled : bool = match &pair_order {
          ForeignPairOrder::Disputed { .. } => true,
          // Agreed, yet folded the other way: the manifests form a cycle.
          ForeignPairOrder::Agreed { first : agreed } => agreed != first,
          ForeignPairOrder::Unlisted => false, };
        if ! unsettled { continue; }
        let spanning_pids : Vec<&ID> = skgrepos_by_pid . iter ()
          . filter ( |(_, skgrepos)| skgrepos . contains (first)
                     && skgrepos . contains (second)
                     && home_owner_of (skgrepos)
                        == Some ( config . skgrepo_owner (first) ))
          . map ( |(pid, _)| pid )
          . collect ();
        if spanning_pids . is_empty () { continue; }
        let why : String = match &pair_order {
          ForeignPairOrder::Disputed { first_by, second_by, .. } => format! (
            "The OTHER_SKGREPO_DEPENDENCIES.toml of foreign repo '{}' lists '{}' first, but that of '{}' lists '{}' first",
            first_by, first, second_by, second ),
          _ => format! (
            "The foreign repos' OTHER_SKGREPO_DEPENDENCIES.toml files order '{}' and '{}' in a cycle with other repos",
            first, second ), };
        warnings . push ( format! (
          "Node {}{} has sections in foreign repos '{}' and '{}'. {}, so this server folds '{}' first, as the manifest of the more private one says. Its publisher's server may fold it otherwise.",
          node_named (config, spanning_pids [0], first),
          more_nodes (spanning_pids . len ()),
          first, second, why, first )); }} }
  warnings }

/// " (and N more nodes)", for COUNT nodes in all.
fn more_nodes (
  count : usize,
) -> String {
  match count . saturating_sub (1) {
    0 => String::new (),
    1 => " (and 1 more node)" . to_string (),
    n => format! (" (and {} more nodes)", n), }}

/// A node, by ID and, when its telescope composes, title.
fn node_named (
  config  : &SkgConfig,
  pid     : &ID,
  skgrepo : &SkgrepoName,
) -> String {
  match graphnode_from_pid_and_skgrepo (
    config, pid . clone (), skgrepo ) {
    Ok (node) => format! ("'{}' ('{}')", pid, node . title),
    Err (_)   => format! ("'{}'", pid), }}

/// For each configured skgrepo, the PIDs of its '.skg' files (their
/// file stems). An unreadable folder contributes none.
fn section_pids_by_skgrepo (
  config : &SkgConfig,
) -> HashMap<SkgrepoName, HashSet<ID>> {
  config . skgrepos . iter ()
    . map ( |(name, skgrepo)| {
        let pids : HashSet<ID> =
          std::fs::read_dir (&skgrepo . path) . into_iter ()
          . flatten () . flatten ()
          . map ( |entry| entry . path () )
          . filter ( |path| path . extension ()
                     . map_or ( false, |ext| ext == "skg" ))
          . filter_map ( |path| path . file_stem ()
                         . map ( |stem| ID::from (
                           stem . to_string_lossy () . into_owned () )) )
          . collect ();
        ( name . clone (), pids ) } )
    . collect () }

