//! OTHER_SKGREPO_DEPENDENCIES.toml: the publisher-side fix for the one structural
//! regression the telescope carries relative to the retired chain
//! design -- a foreign telescope's composition order lives in the
//! receiver's config, not in the data ('docs/api-and-formats.org',
//! "OTHER_SKGREPO_DEPENDENCIES.toml").
//!
//! Publisher half: at init, every owned skgrepo directory gets a
//! OTHER_SKGREPO_DEPENDENCIES.toml whose `dependencies` is a list of pairs, one per
//! Skgrepo its telescope sections may reference -- itself and
//! everything more public, in privacy order, the skgrepo itself last.
//! Each pair says where a receiver can fetch that skgrepo: `path`
//! (data-root-relative, author-namespaced, which is what a receiver
//! actually downloads) and `git-remote` (the skgrepo's fetch URL,
//! `origin` preferred, else the first remote with its name recorded
//! in `git-remote-name`; omitted when the skgrepo is not a gitrepo or
//! has no remote). The last pair is the manifest's own skgrepo, so its
//! own remote falls out for free. skg makes no use of the git-remote
//! values itself. Clobbering a preexisting manifest is a feature;
//! writes are byte-stable.
//!
//! Receiver half: at config validation, a foreign skgrepo carrying a
//! manifest is read, its entries matched to the receiver's skgrepos
//! by final path component (the skgrepo name -- the folder the
//! receiver keeps the publisher's skgrepos in need not match the
//! publisher's own author folder).
//! When the receiver's privacy order contradicts the manifest's
//! relative order of two skgrepos and some telescope this server
//! composes spans both, warn and suggest the fix; never reorder
//! automatically.

use crate::dbs::filesystem::one_node::graphnode_from_pid_and_skgrepo;
use crate::git_ops::read_gitrepo::skgrepo_git_remote;
use crate::types::misc::{ID, SkgConfig, SkgrepoName};

use std::collections::{HashMap, HashSet};
use std::io;
use std::path::PathBuf;

/// Quote a value as a TOML basic string, escaping the two characters
/// that would otherwise break out of the quotes. Enough for git
/// remote URLs and skgrepo paths, which carry no control characters.
fn toml_basic_string (s : &str) -> String {
  let escaped : String =
    s . replace ('\\', "\\\\") . replace ('"', "\\\"");
  format! ("\"{}\"", escaped) }

/// One `dependencies` entry: a skgrepo a manifest's telescope sections
/// may reference, and where a receiver can fetch it.
struct DependencyEntry {
  path   : String,                    // data-root-relative directory
  remote : Option<(String, String)>,  // (remote name, fetch URL)
}

/// Render a `DependencyEntry` as one inline-table line of the
/// `dependencies` list: `{ path = "...", git-remote = "..." },`.
/// `git-remote` is omitted when the skgrepo has no remote;
/// `git-remote-name` appears only for a non-`origin` remote.
fn render_dependency_entry (entry : &DependencyEntry) -> String {
  let mut fields : String =
    format! ("path = {}", toml_basic_string (&entry . path));
  if let Some ((remote_name, remote_url)) = &entry . remote {
    fields . push_str ( & format! (
      ", git-remote = {}", toml_basic_string (remote_url) ));
    if remote_name != "origin" {
      fields . push_str ( & format! (
        ", git-remote-name = {}",
        toml_basic_string (remote_name) )); }}
  format! ("  {{ {} }},\n", fields) }

/// The publisher half. Call after config load; returns the skgrepos
/// whose manifests were (re)written.
pub fn write_dependencies_manifests (
  config : &SkgConfig,
) -> io::Result<Vec<SkgrepoName>> {
  let ordered : Vec<SkgrepoName> = config . ordered_skgrepos ();
  let mut written : Vec<SkgrepoName> = Vec::new ();
  for (position, name) in ordered . iter () . enumerate () {
    if ! config . skgrepo_is_owned (name) { continue; }
    let Some (skgrepo) = config . skgrepos . get (name) else {
      continue; };
    if ! skgrepo . path . is_dir () { continue; }
    let dependencies : Vec<DependencyEntry> =
      ordered [..= position] . iter ()
      . filter_map ( |n| {
          let dep_skgrepo = config . skgrepos . get (n) ?;
          let path : String =
            dep_skgrepo . path
            . strip_prefix ( &config . data_root )
            . map ( |p| p . to_string_lossy () . into_owned () )
            . unwrap_or_else (
              |_| dep_skgrepo . path
                  . to_string_lossy () . into_owned () );
          Some ( DependencyEntry {
            path,
            remote : skgrepo_git_remote (&dep_skgrepo . path), } ) } )
      . collect ();
    let content : String = {
      let mut c : String = String::new ();
      c . push_str (
        "# Generated by skg; regenerated at every server start, so\n\
         # hand edits will be clobbered (that is a feature: it stays\n\
         # true to the publisher's config). Each dependency is a Skg\n\
         # repo this Skg repo's telescope sections may reference --\n\
         # itself and everything more public, MOST PUBLIC FIRST, the\n\
         # Skg repo itself last. A receiver should order these the same\n\
         # way relative to one another, or the privacy telescopes\n\
         # spanning them will compose in the wrong order. `path` is the\n\
         # data-root-relative directory; `git-remote` is where a\n\
         # receiver can fetch it (the fetch URL `git remote -v`\n\
         # prints, `origin` preferred), omitted when the Skg repo is\n\
         # not a Git repo or has no remote; `git-remote-name` names\n\
         # the remote only when it is not the conventional \"origin\".\n\
         # skg makes no use of the git-remote values itself.\n" );
      c . push_str ("dependencies = [\n");
      for entry in &dependencies {
        c . push_str ( & render_dependency_entry (entry) ); }
      c . push_str ("]\n");
      c };
    let manifest_path : PathBuf =
      skgrepo . path . join ("OTHER_SKGREPO_DEPENDENCIES.toml");
    let unchanged : bool = // byte-stability
      std::fs::read_to_string (&manifest_path)
      . map ( |old| old == content )
      . unwrap_or (false);
    if ! unchanged {
      std::fs::write (&manifest_path, content) ?; }
    written . push ( name . clone () ); }
  Ok (written) }

/// The `path` of one `dependencies` entry. New format: an inline
/// table carrying a `path` key. Older format: a bare string. Accept
/// either, so a foreign manifest still in the string shape keeps
/// yielding ordering warnings.
fn dependency_entry_path (e : &toml::Value) -> Option<String> {
  e . as_str () . map ( str::to_string )
    . or_else ( || e . get ("path")
                . and_then ( |p| p . as_str () )
                . map ( str::to_string )) }

/// Two of the receiver's skgrepos that a foreign manifest orders
/// opposite to the receiver's config.
struct ContradictedPair {
  manifest_skgrepo         : SkgrepoName, // the foreign skgrepo shipping the manifest
  more_public_per_manifest : SkgrepoName,
  more_public_per_config   : SkgrepoName,
}

/// The receiver half: warnings (never errors, never reordering) for
/// each pair of skgrepos that a foreign manifest orders opposite to
/// the receiver's config AND that some telescope of this server
/// spans, so that node folds in opposite orders on the two servers.
/// A bare contradiction is not warned about: under the rule that
/// every foreign skgrepo is more public than every owned one, two
/// teammates' configs always order their shared skgrepos oppositely.
/// Returned as strings so 'main' can log them and record them as
/// startup warnings, and tests can pin them.
pub fn foreign_manifest_order_warnings (
  config : &SkgConfig,
) -> Vec<String> {
  let contradicted_pairs : Vec<ContradictedPair> =
    contradicted_pairs_in_foreign_manifests (config);
  if contradicted_pairs . is_empty () {
    return Vec::new (); }
  let section_pids_by_skgrepo : HashMap<SkgrepoName, HashSet<ID>> =
    section_pids_by_skgrepo (config);
  contradicted_pairs . iter ()
    . filter_map ( |pair| {
        let spanning_pids : Vec<ID> =
          pids_whose_telescope_spans_both (
            config, &section_pids_by_skgrepo,
            &pair . more_public_per_manifest,
            &pair . more_public_per_config );
        if spanning_pids . is_empty () { None }
        else { Some ( spanning_telescope_warning (
                        config, pair, &spanning_pids )) }} )
    . collect () }

/// Every pair of the receiver's skgrepos, both named by some foreign
/// manifest, whose relative order there contradicts the receiver's
/// config. Manifest entries match receiver skgrepos by final path
/// component (the skgrepo name).
fn contradicted_pairs_in_foreign_manifests (
  config : &SkgConfig,
) -> Vec<ContradictedPair> {
  let ordered : Vec<SkgrepoName> = config . ordered_skgrepos ();
  let final_component = |p : &std::path::Path| -> Option<String> {
    p . components () . next_back ()
      . and_then ( |c| match c {
        std::path::Component::Normal (s) =>
          Some ( s . to_string_lossy () . into_owned () ),
        _ => None } ) };
  // receiver position by skgrepo name (final path component)
  let receiver_position_of = |gitrepo : &str| -> Option<usize> {
    ordered . iter () . position ( |n|
      config . skgrepos . get (n)
      . and_then ( |s| final_component ( &s . path ))
      . as_deref () == Some (gitrepo) ) };
  let mut pairs : Vec<ContradictedPair> = Vec::new ();
  for name in &ordered {
    if config . skgrepo_is_owned (name) { continue; }
    let Some (skgrepo) = config . skgrepos . get (name) else {
      continue; };
    let manifest_path : PathBuf =
      skgrepo . path . join ("OTHER_SKGREPO_DEPENDENCIES.toml");
    let Ok (contents) =
      std::fs::read_to_string (&manifest_path) else { continue; };
    let entries : Vec<String> =
      toml::from_str::<toml::Value> (&contents) . ok ()
      . as_ref ()
      . and_then ( |v| v . get ("dependencies") )
      . and_then ( |d| d . as_array () )
      . map ( |arr| arr . iter ()
              . filter_map ( dependency_entry_path )
              . collect () )
      . unwrap_or_default ();
    let receiver_positions_in_manifest_order : Vec<usize> =
      // The manifest's entries, restricted to skgrepos the receiver
      // also has.
      entries . iter ()
      . filter_map ( |entry|
          final_component ( std::path::Path::new (entry) ) )
      . filter_map ( |gitrepo| receiver_position_of (&gitrepo) )
      . collect ();
    for (i, earlier) in
      receiver_positions_in_manifest_order . iter () . enumerate () {
      for later in &receiver_positions_in_manifest_order [i + 1 ..] {
        if later < earlier {
          pairs . push ( ContradictedPair {
            manifest_skgrepo         : name . clone (),
            more_public_per_manifest : ordered [*earlier] . clone (),
            more_public_per_config   : ordered [*later] . clone (), } ); }}}}
  pairs }

/// For each configured skgrepo, the PIDs of its '.skg' files (their
/// file stems). An unreadable folder contributes none.
fn section_pids_by_skgrepo (
  config : &SkgConfig,
) -> HashMap<SkgrepoName, HashSet<ID>> {
  config . skgrepos . iter ()
    . map ( |(name, skgrepo)| {
        let pids : HashSet<ID> =
          std::fs::read_dir (&skgrepo . path) . into_iter ()
          . flatten () . flatten ()
          . map ( |entry| entry . path () )
          . filter ( |path| path . extension ()
                     . map_or ( false, |ext| ext == "skg" ))
          . filter_map ( |path| path . file_stem ()
                         . map ( |stem| ID::from (
                           stem . to_string_lossy () . into_owned () )) )
          . collect ();
        ( name . clone (), pids ) } )
    . collect () }

/// The PIDs, sorted, of the telescopes this server composes from a
/// section in each of skgrepos A and B. A PID with an owned section
/// keeps only its owned sections ('retain_owned_sections_when_pid_folderlides'),
/// so an owned and a foreign skgrepo never share a composed
/// telescope, and two foreign ones share one only when no owned
/// skgrepo has a section of that PID.
fn pids_whose_telescope_spans_both (
  config                  : &SkgConfig,
  section_pids_by_skgrepo : &HashMap<SkgrepoName, HashSet<ID>>,
  a                       : &SkgrepoName,
  b                       : &SkgrepoName,
) -> Vec<ID> {
  let a_owned : bool = config . skgrepo_is_owned (a);
  if a_owned != config . skgrepo_is_owned (b) {
    return Vec::new (); }
  let (Some (a_pids), Some (b_pids)) =
    ( section_pids_by_skgrepo . get (a),
      section_pids_by_skgrepo . get (b) )
    else { return Vec::new (); };
  let some_owned_skgrepo_has = |pid : &ID| -> bool {
    section_pids_by_skgrepo . iter ()
    . any ( |(name, pids)| config . skgrepo_is_owned (name)
                           && pids . contains (pid) ) };
  let mut spanning : Vec<ID> =
    a_pids . intersection (b_pids)
    . filter ( |pid| a_owned || ! some_owned_skgrepo_has (pid) )
    . cloned ()
    . collect ();
  spanning . sort ();
  spanning }

/// The warning for one contradicted pair, naming the first spanning
/// node (with its title when its telescope composes) and how many
/// more there are.
fn spanning_telescope_warning (
  config        : &SkgConfig,
  pair          : &ContradictedPair,
  spanning_pids : &[ID],
) -> String {
  let example_pid : &ID = &spanning_pids [0];
  let example_node : String =
    match graphnode_from_pid_and_skgrepo (
      config, example_pid . clone (),
      &pair . more_public_per_config ) {
      Ok (node) => format! ("'{}' ('{}')", example_pid, node . title),
      Err (_)   => format! ("'{}'", example_pid), };
  let more_nodes : String =
    match spanning_pids . len () - 1 {
      0 => String::new (),
      1 => " (and 1 more node)" . to_string (),
      n => format! (" (and {} more nodes)", n), };
  format! (
    "Node {}{} has sections in both '{}' and '{}'. This config orders '{}' more public than '{}', but the OTHER_SKGREPO_DEPENDENCIES.toml of foreign repo '{}' orders them the other way, so that node folds its sections in opposite orders on this server and on that repo's publisher's. For them to agree, one of the two configs must reorder its [[repos]].",
    example_node, more_nodes,
    pair . more_public_per_config, pair . more_public_per_manifest,
    pair . more_public_per_config, pair . more_public_per_manifest,
    pair . manifest_skgrepo ) }

