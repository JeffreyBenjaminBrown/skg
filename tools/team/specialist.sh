#!/usr/bin/env bash
# specialist.sh -- bring a specialist's skg server up or down.
#
#   tools/team/specialist.sh up   NAME   # prints the port and the views folder
#   tools/team/specialist.sh down NAME
#   tools/team/specialist.sh list
#   tools/team/specialist.sh rename OLD NEW  # both servers down; NEW must not exist
#   tools/team/specialist.sh born   NAME "WHO" [JEFFS_NOTE_ID]  # a new specialist, with its home note
#   tools/team/specialist.sh home   NAME HOME_ID     # record its home note, once
#   tools/team/specialist.sh prompt NAME MISSION_ID  # print the prompt that lends it a mind
#
# A specialist is a folder, 'data/claude/team/NAME/', holding its
# skgrepo 'notes/', a config 'skgconfig.toml' that owns only that
# skgrepo, and its views folder 'views/'. The config's folder is its
# data root, so the server keeps its search index, readiness marks and
# run folder there too. Jeff's public skgrepo, Claude's public skgrepo
# and every other specialist's skgrepo are foreign to it, so the
# specialist can read them and can change them only by forking.
# 'up' makes whatever is missing (the skgrepo, its gitrepo, the config,
# a port), starts the server, and starts a skg-for-ai daemon whose
# folder is 'views/'. Nothing here is specific to one specialist; to
# see what one is, read its home note.
#
# Ports are assigned once, in 'data/claude/team/ports', from 1770 up.
# Each line there is 'NAME PORT [HOME_ID]', HOME_ID the specialist's
# home note. 'prompt' prints everything a fresh mind is told: where the
# tool is, its port and views folder, its home note and its mission.
# All it knows beyond that, it reads from the graph.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DATA="$ROOT/data"
TEAM="$DATA/claude/team"
PORTS="$TEAM/ports"
SKG="$ROOT/target/release/skg"
READER="$ROOT/tools/skg-for-ai/skg_for_ai.py"

notes_of() { echo "$TEAM/$1/notes"; } # NAME's skgrepo
views_of() { echo "$TEAM/$1/views"; } # NAME's skg-for-ai folder

usage() {
  echo "usage: tools/team/specialist.sh up|down NAME | list | rename OLD NEW | born NAME WHO [JEFFS_NOTE_ID] | home NAME HOME_ID | prompt NAME MISSION_ID" >&2
  exit 2
}

port_of() { # prints NAME's port, assigning the next free one if it has none
  mkdir -p "$TEAM"; touch "$PORTS"
  local port
  port="$(awk -v n="$1" '$1==n {print $2}' "$PORTS")"
  if [ -z "$port" ]; then
    port="$(awk 'BEGIN{m=1769} $2>m {m=$2} END{print m+1}' "$PORTS")"
    echo "$1 $port" >> "$PORTS"
  fi
  echo "$port"
}

write_config() { # NAME PORT
  # Paths are relative to the config's folder, data/claude/team/NAME/.
  local name="$1" port="$2" config="$TEAM/$1/skgconfig.toml" other
  {
    echo "# Generated by tools/team/specialist.sh; edits are overwritten."
    echo "# The specialist '$name' owns one skgrepo and reads the others."
    echo "tantivy_folder = \".index.tantivy\""
    echo "port = $port"
    echo "timing_log = false"
    echo "beep_when_server_becomes_available = false"
    echo
    printf '[[repos]]\nname = "jeff-public"\npath = "../../../jeff/public"\nforeign = true\n\n'
    printf '[[repos]]\nname = "claude-public"\npath = "../../public"\nforeign = true\n\n'
    for other in "$TEAM"/*/notes/; do
      other="$(basename "$(dirname "$other")")"
      [ "$other" = "$name" ] && continue
      printf '[[repos]]\nname = "%s"\npath = "../%s/notes"\nforeign = true\n\n' "$other" "$other"
    done
    printf '[[repos]]\nname = "%s"\npath = "notes"\n' "$name"
  } > "$config"
  echo "$config"
}

add_to_readers_configs() { # NAME: Claude and Jeff each read every specialist's skgrepo, as foreign
  # Jeff asked, 2026-11-12, that his config be given each new skgrepo.
  # It is the one file of his that this script writes. His running
  # server sees the change at its next rebuild or restart.
  # Each config names the skgrepo relative to its own folder.
  local config path config_and_path
  for config_and_path in "$DATA/claude/skgconfig.toml team/$1/notes" \
                         "$DATA/jeff/skgconfig.toml ../claude/team/$1/notes"; do
    read -r config path <<< "$config_and_path"
    grep -q "path = \"$path\"" "$config" && continue
    # Appended, not prepended: TOML wants the top-level keys before any table.
    {
      printf '\n# The specialist %s. Added by tools/team/specialist.sh.\n' "$1"
      printf '[[repos]]\nname = "%s"\npath = "%s"\nforeign = true\n' "$1" "$path"
    } >> "$config"
    echo "Added '$1' to $config as foreign; its server must rebuild or restart to see it." >&2
  done
}

port_is_bound() { (exec 3<>/dev/tcp/127.0.0.1/"$1") 2>/dev/null; }

up() {
  local name="$1" port config views notes
  port="$(port_of "$name")"
  views="$(views_of "$name")"; notes="$(notes_of "$name")"
  mkdir -p "$notes" "$views"
  if [ ! -d "$notes/.git" ]; then
    # skg's commit compares with HEAD, so a gitrepo needs a first commit.
    git -C "$notes" init -q -b main
    git -C "$notes" config user.name "Claude"
    git -C "$notes" config user.email "noreply@anthropic.com"
    git -C "$notes" commit -q --allow-empty -m "An empty first commit, so that skg's commit has a HEAD to compare with."
  fi
  config="$(write_config "$name" "$port")"
  add_to_readers_configs "$name"
  if ! port_is_bound "$port"; then
    # 'cd' on its own line: after 'cd && nohup ... &', $! would be the
    # pid of a subshell, and 'down' would kill that and leave the server.
    # 'setsid' puts the server in a session of its own, and '< /dev/null'
    # detaches its input, so it outlives the shell that started it
    # (a tool's shell may kill its whole process group when it returns).
    # Not 'setsid -f': it would fork, and $! would not be the server.
    ( cd "$ROOT"
      setsid nohup "$SKG" "$config" > "$views/server.log" 2>&1 < /dev/null &
      echo $! > "$views/server.pid" )
    for _ in $(seq 1 60); do
      grep -q "Server ready" "$views/server.log" 2>/dev/null && break
      sleep 0.5
    done
    grep -q "Server ready" "$views/server.log" \
      || { echo "The server for '$name' did not become ready; see $views/server.log" >&2; exit 1; }
  fi
  if [ ! -S "$views/skg-for-ai.sock" ] || ! pgrep -f "daemon --out-dir $views" >/dev/null; then
    rm -f "$views/skg-for-ai.sock"
    ( setsid nohup python3 "$READER" daemon --out-dir "$views" --port "$port" \
        > "$views/daemon.out" 2>&1 < /dev/null & )
    sleep 1
  fi
  echo "port=$port"
  echo "views=$views"
}

down() {
  local name="$1" views; views="$(views_of "$1")"
  python3 "$READER" daemon --stop --out-dir "$views" >/dev/null 2>&1 || true
  if [ -f "$views/server.pid" ]; then
    kill "$(cat "$views/server.pid")" 2>/dev/null || true
    rm -f "$views/server.pid"
  fi
  echo "down: $name"
}

rename_in_readers_config() { # CONFIG OLD NEW OLD_PATH NEW_PATH: one skgrepo's name and path
  # Jeff's config is the one file of his that this script writes.
  # The comment line that add_to_readers_configs put above the entry is kept true too.
  [ -f "$1" ] || return 0
  sed -i -e "s|^name = \"$2\"\$|name = \"$3\"|" \
         -e "s|^path = \"$4\"\$|path = \"$5\"|" \
         -e "s|^# The specialist $2\\. Added by|# The specialist $3. Added by|" "$1"
}

rename() { # OLD NEW: the folder, the ports line, and the readers' configs; the rest is rebuilt by 'up'
  local old="$1" new="$2" name
  [ -d "$TEAM/$old" ] || { echo "No specialist '$old'." >&2; exit 1; }
  [ ! -e "$TEAM/$new" ] || { echo "'$new' already exists." >&2; exit 1; }
  grep -q "^$new " "$PORTS" && { echo "'$new' is already in $PORTS." >&2; exit 1; }
  for name in "$old" "$new"; do
    if grep -q "^$name " "$PORTS" && port_is_bound "$(awk -v n="$name" '$1==n {print $2}' "$PORTS")"; then
      echo "The server of '$name' is running; 'down' it first." >&2; exit 1
    fi
  done
  python3 "$READER" daemon --stop --out-dir "$(views_of "$old")" >/dev/null 2>&1 || true
  mv "$TEAM/$old" "$TEAM/$new"
  # The search index and the run folders were made under the old name; 'up' rebuilds them.
  rm -rf "$TEAM/$new/.index.tantivy" "$TEAM/$new/skgconfig.toml.running"
  awk -v o="$old" -v n="$new" '$1==o {$1=n} {print}' "$PORTS" > "$PORTS.tmp"
  mv "$PORTS.tmp" "$PORTS"
  rename_in_readers_config "$DATA/claude/skgconfig.toml" "$old" "$new" "team/$old/notes" "team/$new/notes"
  rename_in_readers_config "$DATA/jeff/skgconfig.toml" "$old" "$new" "../claude/team/$old/notes" "../claude/team/$new/notes"
  # Its own config is regenerated by 'up', and so are the other specialists' configs,
  # which write_config builds from the folders that exist.
  write_config "$new" "$(port_of "$new")" >/dev/null
  echo "Renamed '$old' to '$new'. Other specialists' configs name it at their next 'up'." >&2
}

BOOT_NOTE="43b33774-4571-48cc-ae01-0a26dbeb113d" # Claude's "working here as a specialist"

born() { # NAME WHO [JEFFS_NOTE_ID]: 'up', then a home note of the standard shape
  local name="$1" who="$2" jeffs="${3:-}" port views title home view
  if [ -n "$(awk -v n="$name" '$1==n {print $3}' "$PORTS" 2>/dev/null)" ]; then
    echo "'$name' already has a home note" >&2; exit 1
  fi
  up "$name"
  port="$(port_of "$name")"; views="$(views_of "$name")"
  title="$(echo "${name:0:1}" | tr '[:lower:]' '[:upper:]')${name:1}"
  home="$(python3 "$READER" new "$title" "$name" --port "$port" --out-dir "$views" \
            | awk '/^New node:/ {print $3}')"
  [ -n "$home" ] || { echo "could not create the home note of '$name'" >&2; exit 1; }
  view="$views/view_$home"
  # A new root has no containers folder, so appending to its view is safe.
  {
    echo "$who"
    [ -n "$jeffs" ] && echo "** what Jeff asked of me ⟨node:$jeffs⟩"
    echo "** working here ⟨node:$BOOT_NOTE⟩"
    echo "** what I know"
    echo "** to Claude"
  } >> "$view.compact.org"
  python3 "$READER" save "$view.view.json" --yes --port "$port" | grep -E "^Server|Error" >&2
  set_home "$name" "$home"
  python3 "$READER" commit "$title is born: a home note" --yes --port "$port" | tail -1 >&2
  echo "home=$home"
}

set_home() { # NAME HOME_ID
  port_of "$1" >/dev/null
  awk -v n="$1" -v h="$2" '$1==n {print $1, $2, h; next} {print}' "$PORTS" > "$PORTS.tmp"
  mv "$PORTS.tmp" "$PORTS"
}

prompt() { # NAME MISSION_ID
  local name="$1" mission="$2" port home
  port="$(awk -v n="$name" '$1==n {print $2}' "$PORTS")"
  home="$(awk -v n="$name" '$1==n {print $3}' "$PORTS")"
  [ -n "$port" ] && [ -n "$home" ] \
    || { echo "'$name' has no port or no home note in $PORTS" >&2; exit 1; }
  cat <<PROMPT
You are being lent to a specialist named $name, on the team that builds skg (a knowledge-graph editor whose code is at $ROOT). Everything $name knows is in $name's knowledge graph, which you read and write with a command-line tool.

Work from $ROOT. $name's skg server is already running. Your port is $port and your views folder is data/claude/team/$name/views. Every command is

  python3 tools/skg-for-ai/skg_for_ai.py COMMAND ... --port $port --out-dir data/claude/team/$name/views

Do these in order:

1. Read the first page ("Start here") of tools/skg-for-ai/README.org, so you can view and save notes. One thing that page does not say: when adding to a view file, insert new headlines under the headline they belong to; do not append them to the end of the file, because a view can end in a write-protected folder listing the root's containers.

2. Read your home note: view $home. It says who $name is and how a specialist works here. Follow what it says.

3. Read your mission: view $mission. Then do it.

When you finish, your final message should be one or two sentences. Everything else belongs in the graph, as your home note explains.
PROMPT
}

case "${1:-}" in
  up)   [ $# -eq 2 ] || usage; up "$2" ;;
  down) [ $# -eq 2 ] || usage; down "$2" ;;
  list) cat "$PORTS" 2>/dev/null || true ;;
  rename) [ $# -eq 3 ] || usage; rename "$2" "$3" ;;
  born)   [ $# -ge 3 ] || usage; born "$2" "$3" "${4:-}" ;;
  home)   [ $# -eq 3 ] || usage; set_home "$2" "$3" ;;
  prompt) [ $# -eq 3 ] || usage; prompt "$2" "$3" ;;
  *)    usage ;;
esac
